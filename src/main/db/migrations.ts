interface Migration {
  version: number
  name: string
  sql: string
}

const BREAKPOINT_RE = /^\s*--> statement-breakpoint\s*$/m

/**
 * Executes a drizzle-kit generated SQL file. The file separates statements with
 * `--> statement-breakpoint` comment markers (not valid SQL), so it is split on
 * those markers and each statement is executed independently — matching how the
 * generated file is laid out.
 */
function applySql(db: DatabaseSync, sql: string): void {
  const statements = sql
    .split(BREAKPOINT_RE)
    .map((s) => s.trim())
    .filter(Boolean)
  for (const statement of statements) {
    db.exec(statement)
  }
}

/**
 * Applies pending migrations in version order, recording each in
 * `schema_migrations` only after it succeeds. The whole run is atomic: a
 * failing migration rolls everything back (SQLite DDL is transactional), so a
 * partially migrated schema is never left behind. Legacy databases created by
 * the pre-Drizzle runner are reconciled by marking version 0 applied without
 * executing it.
 */
export function runMigrations(): void {
  const db: DatabaseSync = getDb()

  withTransaction(() => {
    db.exec(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        version INTEGER PRIMARY KEY,
        name TEXT NOT NULL,
        applied_at TEXT NOT NULL DEFAULT (datetime('now'))
      );
    `)

    const applied = new Set(
      (db.prepare('SELECT version FROM schema_migrations').all() as { version: number }[]).map(
        (r) => r.version
      )
    )

    if (!applied.has(0)) {
      const hasLegacyTables =
        db
          .prepare(
            `SELECT 1 AS x FROM sqlite_master
             WHERE type = 'table' AND name = 'organizations'`
          )
          .get() !== undefined
      if (hasLegacyTables) {
        db.prepare('INSERT INTO schema_migrations (version, name) VALUES (?, ?)').run(0, 'identity')
        applied.add(0)
      }
    }

    const insert = db.prepare('INSERT INTO schema_migrations (version, name) VALUES (?, ?)')

    for (const migration of migrations) {
      if (applied.has(migration.version)) continue
      applySql(db, migration.sql)
      insert.run(migration.version, migration.name)
    }
  })
}
